# 整数的表示
a = 100
# 对于很大的数，例如 10000000000 ，很难数清楚0的个数。Python允许在数字中间以 _ 分隔，因此，写成 10_000_000_000 和 10000000000 是完全一样的。

# 浮点数的表示
b = 3.14
# 浮点数也可以用科学计数法表示，例如 3.14e10 表示 3.14 × 10^10。
c = 3.14e10

# 字符串的表示，是以单引号或双引号括起来的字符序列。
d = 'Hello, World!'
e = "Python"
# 字符串内也包含'和"字符时，可以使用转义字符\，例如：
f = 'I\'m a student.'
print(f)  # 输出：I'm a student.

# 转义字符 \ 本身
# 如果字符串中包含 \ 字符本身，可以使用两个反斜杠 \\ 来表示一个反斜杠，例如：
print('\\\n\\') # 输出换行的两个 \
print('\\\t\\') # 输出制表符的两个 \
# 允许使用r''或r""表示原始字符串，原始字符串中的转义字符不会被转义，例如：
print(r'\\\n\\') # 输出：\\\n\\

# 允许使用三引号表示多行字符串，例如：
print('''This is a multi-line string.
It can span multiple lines.''')

print('''hello,\n
world''')

# 布尔值，只有两个值 True 和 False，注意首字母大写。
# 逻辑运算符包括 and、or 和 not，例如：
x = True
y = False
print(x and y)  # 输出：False
print(x or y)   # 输出：True
print(not x)    # 输出：False

# 空值 None，表示没有值或空值，和 0 不同，也和 False 不同。None 是一个特殊的常量，通常用于表示缺失或未定义的值。

# 变量，python是动态语言，变量不需要声明类型，变量的类型是根据赋值来决定的。

# 常量，Python没有内置的常量类型，但可以通过命名约定来表示常量，例如使用全大写字母表示常量：
PI = 3.14159
# 但事实上 PI 仍然是一个变量，Python根本没有任何机制保证 PI 不会被改变，所以，用全部大写的变量名表示常量只是一个习惯上的用法

# python中，整数的除法是精确的
print(10 // 3)  # 输出：3，只取整数部分
print(10 / 3)   # 输出：3.3333333333333335，结果始终是浮点数，即使两个整数相除，结果也会是浮点数
print(10 % 3)   # 输出：1，取余