# 写文件和读文件是一样的，唯一区别是调用open()函数时，传入标识符'w'或者'wb'表示写文本文件或写二进制文件
# 最保险的方法是用with语句
# 'w'表示写入的内容覆盖已有的，'a'表示追加
with open('test.txt', 'a') as t:
    t.write('hello, world!')

